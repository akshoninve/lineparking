// Список "Месяц Год" для выпадающего списка в форме оплаты и в админке,
// например "Январь 2026". Год зашит явно, чтобы не путать оплату за
// один и тот же месяц в разные годы.
//
// Список — скользящее окно вокруг текущей даты: 6 месяцев назад и
// 5 месяцев вперёд (12 вариантов вместе с текущим), а не фиксированный
// список на весь календарный год — так он не "протухает" под конец
// года и не разрастается бесконечно, автоматически сдвигаясь каждый
// месяц вместе с датой на сервере.
$monthWindowBack    = 6; // месяцев назад от текущего
$monthWindowForward = 5; // месяцев вперёд от текущего (итого 12 вариантов)

$months = [];
$monthCursor = new DateTime('first day of this month');
$monthCursor->modify("-{$monthWindowBack} months");
for ($i = 0; $i < $monthWindowBack + $monthWindowForward + 1; $i++) {
    $months[] = $monthNames[(int)$monthCursor->format('n') - 1] . ' ' . $monthCursor->format('Y');
    $monthCursor->modify('+1 month');
}

