<?php
/**
 * includes/log-reader.php
 * Чтение и разбор лога заявок (zayavki.log) для админ-панели:
 * сопоставляет оплаченные/неоплаченные машино-места по каждой
 * парковке за выбранный месяц (шахматка), а также отдаёт плоский
 * хронологический список заявок за месяц (журнал событий).
 *
 * Формат строки лога (одна заявка — одна строка JSON) в файле
 * zayavki-<год>.log, см. includes/form-handler.php и result.php
 * (обработчик ResultURL-уведомлений Robokassa, который дописывает
 * payment_id и меняет status на "оплачено"):
 *   {"date":"...", "fio":"...", "phone":"...", "parking":"Парковка «Левитан»",
 *    "spot":"2", "month":"Январь", "amount":12000, "tariff":"...",
 *    "payment_id":"...", "status":"оплачено"}
 */

/**
 * Читает лог заявок и возвращает записи.
 *
 * Лог ротируется по годам: zayavki-2026.log, zayavki-2027.log и т.д.
 * (см. includes/form-handler.php) — при ~500 местах на 12 месяцев это
 * несколько тысяч строк в год, поэтому один файл на всё время работы
 * сайта был бы слишком большим и его неудобно архивировать.
 *
 * Админка (admin/index.php) всегда показывает статус ровно за ОДИН
 * выбранный месяц — значит и читать нужно только файл ТОГО года, к
 * которому этот месяц относится, а не всю историю сайта. Поэтому
 * функция принимает необязательный параметр $year: если он передан,
 * читается только zayavki-<year>.log (+ legacy-файл без года, если
 * остался с версии до введения ротации — он один на всё время и
 * дальше не растёт, поэтому читать его всегда безопасно). Так объём
 * чтения на каждой загрузке админки не зависит от того, сколько лет
 * подряд уже работает сайт — он ограничен данными одного года.
 *
 * Если $year не передан — читаются ВСЕ годовые файлы (используется
 * и в шахматке, и в журнале событий — обе фичи фильтруют по месяцу,
 * а не по году, поэтому год заранее не известен).
 *
 * Файлы читаются в хронологическом порядке (сначала старый
 * нередактированный zayavki.log, если он ещё остался с прошлых
 * версий, затем zayavki-YYYY.log по возрастанию года) — это важно,
 * т.к. getSpotStatusesForMonth() считает актуальной последнюю
 * встреченную запись по месту+месяцу, а resolveSpotDisplay() смотрит
 * на ВСЕ записи по месту+месяцу (в т.ч. чтобы найти дубли оплаты).
 * По той же причине порядок важен и для журнала событий
 * (getEntriesForMonth() ниже) — записи в нём идут в том же порядке,
 * в каком дописывались в лог, без отдельной пересортировки.
 * Повреждённые/нераспознанные строки молча пропускаются, чтобы
 * одна битая строка не ломала всю админку.
 */
function loadZayavkiLog(?string $year = null): array {
    if (!defined('LOGS_PATH')) {
        return [];
    }

    $files = [];

    // Старый файл без ротации (мог остаться с версии до введения
    // ротации по годам) — читаем первым, в нём самые ранние записи.
    // Он конечен и не растёт дальше, поэтому включаем его всегда,
    // независимо от того, какой год запрошен.
    $legacy = LOGS_PATH . '/zayavki.log';
    if (is_readable($legacy)) {
        $files[] = $legacy;
    }

    if ($year !== null) {
        // Нужен только файл конкретного года — именно это и экономит
        // чтение при растущей многолетней истории заявок.
        $yearlyPath = LOGS_PATH . '/zayavki-' . $year . '.log';
        if (is_readable($yearlyPath)) {
            $files[] = $yearlyPath;
        }
    } else {
        // Годовые файлы: сортируем по имени — 'zayavki-2026.log' <
        // 'zayavki-2027.log' лексикографически совпадает с хронологией,
        // т.к. год всегда 4 цифры.
        $yearly = glob(LOGS_PATH . '/zayavki-*.log') ?: [];
        sort($yearly, SORT_STRING);
        $files = array_merge($files, $yearly);
    }

    $entries = [];
    foreach ($files as $path) {
        if (!is_readable($path)) {
            continue;
        }
        $lines = file($path, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES);
        if ($lines === false) {
            continue;
        }
        foreach ($lines as $line) {
            $entry = json_decode($line, true);
            if (is_array($entry)) {
                $entries[] = $entry;
            }
        }
    }
    return $entries;
}

/**
 * Проверяет, относится ли заявка к запрошенному месяцу ("Месяц Год",
 * например "Октябрь 2026").
 *
 * Для обычной помесячной оплаты это просто entry['month'] === $month.
 *
 * Для оплаты за несколько дней, которая пересекает границу
 * календарного месяца (includes/form-handler.php,
 * includes/functions.php::monthLabelsForPeriod()), заявка физически
 * ОДНА (один payment_id, одна строка в логе), но должна "занимать"
 * место сразу во ВСЕХ месяцах, которые затрагивает период — иначе,
 * скажем, октябрьская часть периода "28 сентября – 3 октября" была бы
 * не видна в шахматке за октябрь, и место могло бы уйти второй заявке.
 * Поэтому такие заявки дополнительно несут entry['months'] — список всех
 * затронутых месяцев, — и здесь проверяется вхождение в этот список.
 *
 * entry['months'] отсутствует у обычных (не дневных) и у старых записей
 * лога, сделанных до появления этой фичи — для них просто сравниваем
 * entry['month'] напрямую, как и раньше.
 */
function entryCoversMonth(array $entry, string $month): bool {
    if (isset($entry['months']) && is_array($entry['months'])) {
        return in_array($month, $entry['months'], true);
    }
    return ($entry['month'] ?? null) === $month;
}

/**
 * Карта "отображаемое имя парковки" => "ключ парковки" ('levitan' и т.д.),
 * т.к. в логе хранится имя (form-handler.php пишет $parkings[$key][0]),
 * а не сам ключ.
 */
function buildParkingNameToKeyMap(array $parkings): array {
    $map = [];
    foreach ($parkings as $key => [$name, $capacity]) {
        $map[$name] = $key;
    }
    return $map;
}

/**
 * Возвращает ВСЕ заявки по каждому машино-месту за конкретный месяц
 * по каждой парковке:
 *   [
 *     'levitan' => [
 *        1 => [ ...заявка1..., ...заявка2... ],  // 0+ заявок за этот месяц,
 *        2 => [ ...заявка... ],                  // в хронологическом порядке
 *        3 => [],                                // пусто — заявок не было
 *        ...
 *     ],
 *     'kupelinka' => [...],
 *   ]
 *
 * Раньше эта функция схлопывала все заявки по месту+месяцу в одну
 * (побеждала последняя) — этого было достаточно для статуса "оплачено/
 * ожидает/пусто", но невозможно было заметить ситуацию, когда одно и
 * то же место случайно оплатили дважды (например, клиент дважды нажал
 * "Оплатить" или вручную перевёл деньги, уже имея заявку с успешной
 * онлайн-оплатой). Теперь функция сохраняет весь список заявок по
 * месту, а решение о том, что показывать (обычный статус или "дубль
 * оплаты"), принимает resolveSpotDisplay() ниже — так админка может
 * явно предупредить о повторной оплате и показать оба платежа.
 */
function getSpotStatusesForMonth(array $entries, array $parkings, string $month): array {
    $nameToKey = buildParkingNameToKeyMap($parkings);

    $result = [];
    foreach ($parkings as $key => [$name, $capacity]) {
        $result[$key] = array_fill(1, $capacity, []);
    }

    foreach ($entries as $entry) {
        if (!entryCoversMonth($entry, $month)) {
            continue;
        }
        $key = $nameToKey[$entry['parking'] ?? ''] ?? null;
        if ($key === null) {
            continue;
        }
        $spot = (int)($entry['spot'] ?? 0);
        if ($spot < 1 || !array_key_exists($spot, $result[$key])) {
            continue;
        }
        $result[$key][$spot][] = $entry;
    }

    return $result;
}

/**
 * Определяет, как показать одно машино-место в админке, на основе
 * СПИСКА всех его заявок за месяц (см. getSpotStatusesForMonth()) и
 * самого запрошенного месяца.
 *
 * Возвращает:
 *   [
 *     'state'       => 'empty' | 'paid' | 'paid-period' | 'pending' | 'duplicate',
 *     'entry'       => заявка для карточки деталей | null,
 *     'paidEntries' => все заявки со статусом "оплачено" (для 'duplicate'),
 *   ]
 *
 * 'duplicate' — особый статус: заявок со статусом "оплачено" по этому
 * месту и месяцу ДВЕ и более. Это значит, что за одно и то же место
 * за один и тот же месяц прошло два (или больше) реальных платежа —
 * почти наверняка ошибка (двойное списание у клиента, дублирующая
 * заявка и т.п.), которую стоит проверить вручную и, возможно,
 * вернуть деньги за лишний платёж.
 *
 * 'paid' vs 'paid-period' — оба означают "оплачено", различие чисто
 * по СПОСОБУ оплаты, не по тому, в каком месяце возник счёт:
 *   'paid'        — обычная помесячная оплата (entry['period'] пусто);
 *   'paid-period' — оплата произвольными датами (entry['period']
 *                    заполнено, см. includes/form-handler.php) — сюда
 *                    попадает и месяц, где стоит счёт, и попутные
 *                    месяцы того же периода, если он пересекает
 *                    границу месяца: цвет в шахматке одинаковый для
 *                    всех месяцев одного такого платежа, отличается
 *                    только от обычной помесячной оплаты.
 *
 * ВАЖНО (исправлено): если оплаченная заявка РОВНО ОДНА, место
 * считается оплаченным — вне зависимости от того, создавались ли
 * позже другие, неоплаченные заявки на то же место и месяц. Раньше
 * статус брался у ПОСЛЕДНЕЙ по времени заявки, что приводило к
 * ошибке: если клиент (или кто-то ещё) отправлял повторную заявку на
 * уже оплаченное место — например, по ошибке или на всякий случай
 * "перепроверить" форму — место в шахматке откатывалось на "ожидает
 * оплаты", хотя деньги фактически были получены. Оплата — необратимый
 * факт, и более поздняя незавершённая заявка не должна его скрывать.
 */
function resolveSpotDisplay(array $spotEntries, string $month): array {
    if (empty($spotEntries)) {
        return ['state' => 'empty', 'entry' => null, 'paidEntries' => []];
    }

    $paidEntries = array_values(array_filter(
        $spotEntries,
        fn($e) => ($e['status'] ?? '') === 'оплачено'
    ));

    if (count($paidEntries) >= 2) {
        return [
            'state'       => 'duplicate',
            'entry'       => end($spotEntries),
            'paidEntries' => $paidEntries,
        ];
    }

    if (count($paidEntries) === 1) {
        $isDatedPayment = !empty($paidEntries[0]['period']);
        return [
            'state'       => $isDatedPayment ? 'paid-period' : 'paid',
            'entry'       => $paidEntries[0],
            'paidEntries' => $paidEntries,
        ];
    }

    // Оплаченных заявок нет вовсе — показываем статус последней по
    // времени (обычно "ожидает оплаты", но подстрахуемся и на случай
    // других будущих статусов).
    $last = end($spotEntries);
    return ['state' => 'pending', 'entry' => $last, 'paidEntries' => $paidEntries];
}

/**
 * Короткая сводка по парковке за месяц: сколько мест оплачено помесячно /
 * оплачено произвольными датами / ожидает оплаты (или другой
 * незавершённый статус) / без заявок вовсе / оплачено дважды и более
 * (см. resolveSpotDisplay()), а также выручка.
 *
 * 'revenue' — сумма amount по заявкам, у которых ИМЕННО ЭТОТ месяц —
 * "родной" (entry['month'], первый месяц периода — см.
 * includes/form-handler.php), плюс все заявки в 'duplicate' (это
 * реально поступившие деньги, а не расчётная стоимость мест). Попутные
 * месяцы многомесячного периода в revenue НЕ засчитываются — иначе
 * один и тот же платёж прибавлялся бы к выручке в каждом затронутом
 * месяце (например, платёж на 4 месяца утроил/учетверил бы выручку).
 * Поэтому revenue может не совпадать с paid * pricePerMonth, если есть
 * дубли оплаты или многомесячные периоды — это ожидаемо.
 */
function summarizeParkingStatuses(array $spotStatuses, string $month): array {
    $summary = ['paid' => 0, 'paidPeriod' => 0, 'pending' => 0, 'empty' => 0, 'duplicate' => 0, 'total' => count($spotStatuses), 'revenue' => 0];
    foreach ($spotStatuses as $spotEntries) {
        $resolved = resolveSpotDisplay($spotEntries, $month);
        if ($resolved['state'] === 'paid-period') {
            $summary['paidPeriod']++;
        } else {
            $summary[$resolved['state']]++;
        }
        foreach ($resolved['paidEntries'] as $paidEntry) {
            if (($paidEntry['month'] ?? null) === $month) {
                $summary['revenue'] += (float)($paidEntry['amount'] ?? 0);
            }
        }
    }
    return $summary;
}

/**
 * Журнал событий: плоский список ВСЕХ заявок за конкретный месяц
 * (по всем парковкам сразу), без группировки по месту — в отличие
 * от getSpotStatusesForMonth(), который раскладывает заявки по
 * сетке "парковка → место". Нужен, чтобы увидеть очерёдность и
 * детали заявок так, как они реально шли одна за другой, а не
 * только текущий статус конкретного места.
 *
 * Порядок НЕ пересортировывается: он такой же, как в loadZayavkiLog()
 * (т.е. хронологический — так, как строки дописывались в лог), array_filter()
 * сохраняет исходный порядок элементов.
 */
function getEntriesForMonth(array $entries, string $month): array {
    return array_values(array_filter(
        $entries,
        fn($e) => entryCoversMonth($e, $month)
    ));
}
